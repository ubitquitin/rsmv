#!/usr/bin/env python3
"""Pack only collision tiles from collision_X_Z_PLANE.lua into indexed Lua shards.

Format: 4096 unsigned 9-bit collision values (4608 bytes), followed by an
optional 512-byte missing-cell bitmap when any input collision value is -1.
Missing cells are stored as zero in the packed values and flagged in bitmap.
"""
import argparse
import base64
import re
from pathlib import Path

NAME = re.compile(r'^collision_(-?\d+)_(-?\d+)_(-?\d+)\.lua$')
GRID = re.compile(r'\{([^{}]*)\}')
NUM = re.compile(r'-?\d+')
PACKED_BYTES = 4096 * 9 // 8  # 4608


def extract_grid(text, field, path):
    m = re.search(r'\b' + re.escape(field) + r'\s*=\s*\{', text)
    if not m:
        raise ValueError(f'{path}: missing {field}')
    start = m.end() - 1
    depth = 0
    end = None
    for i in range(start, len(text)):
        if text[i] == '{':
            depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0:
                end = i
                break
    if end is None:
        raise ValueError(f'{path}: unclosed {field}')
    body = text[start + 1:end]
    rows = []
    for match in GRID.finditer(body):
        row = [int(v) for v in NUM.findall(match.group(1))]
        if len(row) != 64:
            raise ValueError(f'{path}: {field} row {len(rows)} has {len(row)} cells')
        rows.append(row)
    if len(rows) != 64:
        raise ValueError(f'{path}: {field} has {len(rows)} rows')
    return [v for row in rows for v in row]


def encode(text, path):
    collision = extract_grid(text, 'tiles', path)
    packed = bytearray()
    missing = bytearray(512)
    bits = accumulator = missing_count = 0
    for i, c in enumerate(collision):
        if c == -1:
            missing[i // 8] |= 1 << (i % 8)
            missing_count += 1
            c = 0
        if not 0 <= c <= 511:
            raise ValueError(f'{path}: tile {i} out of range: collision={c}')
        accumulator |= c << bits
        bits += 9
        while bits >= 8:
            packed.append(accumulator & 255)
            accumulator >>= 8
            bits -= 8
    if bits:
        packed.append(accumulator & 255)
    assert len(packed) == PACKED_BYTES
    if missing_count:
        packed.extend(missing)
    return base64.b64encode(packed).decode('ascii'), missing_count


def write_shard(output, number, records):
    path = output / f'maps_{number:03d}.lua'
    with path.open('w', encoding='ascii', newline='\n') as f:
        f.write('-- Generated by pack_maps_collision_only.py; do not edit.\nreturn {\n')
        for key, encoded in records:
            f.write(f'  ["{key}"] = "{encoded}",\n')
        f.write('}\n')
    return path.stat().st_size


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('input', type=Path, help='Directory containing collision_X_Z_PLANE.lua')
    ap.add_argument('output', type=Path, help='Output directory for maps_NNN.lua and index.lua')
    ap.add_argument('--max-mb', type=float, default=50, help='Max Lua shard size in MiB (default 50)')
    ap.add_argument('--limit', type=int, default=0, help='Only convert first N files (for testing)')
    args = ap.parse_args()
    if args.input.resolve() == args.output.resolve():
        ap.error('input and output must differ')
    args.output.mkdir(parents=True, exist_ok=True)
    files = []
    for p in args.input.iterdir():
        m = NAME.match(p.name)
        if m:
            files.append((tuple(map(int, m.groups())), p))
    files.sort()
    if args.limit:
        files = files[:args.limit]
    if not files:
        ap.error('No collision_X_Z_PLANE.lua files found')
    max_bytes = int(args.max_mb * 1024 * 1024)
    if max_bytes < 10000:
        ap.error('--max-mb must allow at least one mapsquare')
    records, current_size, shard = [], len('return {\n}\n'), 1
    index, shard_sizes = {}, []
    missing_total = 0
    for i, ((x, z, plane), path) in enumerate(files, 1):
        key = f'{x}_{z}_{plane}'
        encoded, missing_count = encode(path.read_text(encoding='utf-8-sig'), path)
        missing_total += missing_count
        line_size = len(encoded) + len(key) + 14
        if records and current_size + line_size > max_bytes:
            shard_sizes.append(write_shard(args.output, shard, records))
            print(f'Wrote maps_{shard:03d}.lua ({len(records)} mapsquares)')
            shard += 1
            records, current_size = [], len('return {\n}\n')
        records.append((key, encoded))
        index[key] = shard
        current_size += line_size
        if i % 1000 == 0:
            print(f'Encoded {i}/{len(files)} mapsquares')
    if records:
        shard_sizes.append(write_shard(args.output, shard, records))
    with (args.output / 'index.lua').open('w', encoding='ascii', newline='\n') as f:
        f.write('-- Generated map index. Key: mapsquareX_mapsquareZ_plane; value: shard number.\n')
        f.write('return {\n')
        for key, shard_no in index.items():
            f.write(f'  ["{key}"] = {shard_no},\n')
        f.write('}\n')
    print(f'Done: {len(files)} mapsquares, {shard} shards, '
          f'{sum(shard_sizes)/1048576:.2f} MiB encoded, {missing_total} missing collision cells')


if __name__ == '__main__':
    main()
