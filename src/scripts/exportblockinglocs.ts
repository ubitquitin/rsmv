import * as fs from "fs/promises";
import * as path from "path";
import { EngineCache } from "../3d/modeltothree";
import { cacheMajors } from "../constants";
import { mappedFileIds } from "../cache";
import { parse } from "../parser/jsondecoders";
import type { CacheFileSource } from "../cache";

export async function exportBlockingLocs(
    source: CacheFileSource,
    outputDir: string
) {
    const engine = await EngineCache.create(source);

    if (engine.classicData || engine.getBuildNr() < 759) {
        throw new Error("This exporter supports RS3 caches build 759+ only.");
    }

    const index = await engine.getCacheIndex(cacheMajors.locs);
    const stride = mappedFileIds[cacheMajors.locs];

    const blockingIds: number[] = [];

    let total = 0;
    let missing = 0;
    let nonblocking = 0;
    let failed = 0;

    for (const entry of index) {
        if (!entry) continue;

        const archive = await engine.getFileArchive(entry);

        for (const file of archive) {
            const id = entry.minor * stride + file.fileid;
            total++;

            try {
                const loc = parse.loc.read(file.buffer, engine);

                if (loc.blocks_movement === true) {
                    blockingIds.push(id);
                } else if (loc.blocks_movement == null) {
                    missing++;
                } else {
                    nonblocking++;
                }
            } catch (err) {
                failed++;
                console.error(`Failed to decode Loc ${id}:`, err);
            }
        }
    }

    // Do not silently publish an incomplete lookup.
    if (failed > 0) {
        throw new Error(`${failed} Loc configurations failed to decode.`);
    }

    blockingIds.sort((a, b) => a - b);

    await fs.mkdir(outputDir, { recursive: true });

    // JSON list for offline analysis.
    const json = JSON.stringify(blockingIds);

    await fs.writeFile(
        path.join(outputDir, "blocking_locs.json"),
        json,
        "utf8"
    );

    // Lua hash set for runtime membership checks.
    const lua = [
        "-- Generated by exportblockinglocs.ts; do not edit.",
        `-- Cache build: ${engine.getBuildNr()}`,
        "return {",
        ...blockingIds.map(id => `    [${id}] = true,`),
        "}",
        ""
    ].join("\n");

    await fs.writeFile(
        path.join(outputDir, "blocking_locs.lua"),
        lua,
        "utf8"
    );

    const maxId = blockingIds.length
        ? blockingIds[blockingIds.length - 1]
        : -1;

    const stats = {
        cacheBuild: engine.getBuildNr(),
        totalLocs: total,
        blockingLocs: blockingIds.length,
        nonblockingLocs: nonblocking,
        missingProperty: missing,
        failedDecodes: failed,
        maxBlockingId: maxId,
        blockingPercentage: total
            ? 100 * blockingIds.length / total
            : 0,
        jsonBytes: Buffer.byteLength(json),
        luaBytes: Buffer.byteLength(lua),
        estimatedBitsetBytes: Math.ceil((maxId + 1) / 8)
    };

    await fs.writeFile(
        path.join(outputDir, "blocking_locs_stats.json"),
        JSON.stringify(stats, null, 2),
        "utf8"
    );

    console.log(stats);

    return stats;
}